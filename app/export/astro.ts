/**
 * Target 2 — **a runnable, editable Astro project** (D24, §11.1).
 *
 * The point of D24 is that the client bought the code: a pre-built `dist/` with the
 * source stripped turns every future typo into a rebuild request to us. So the tree is
 * the *source* of a static site:
 *
 *     src/pages/about.astro          one page, one frontmatter block, one component call
 *     src/content/pages/about.html   that page's body fragment — the bytes an editor edits
 *     src/components/Shell.astro     the same document the product serves
 *     public/media/**                the bytes at the URL the render derived
 *
 * `Shell.astro` is `app/render/components/shells/page.astro` with its props lifted: the
 * site passes `{page}`, the export passes `{title, path, css, body}`. Its **output** is
 * byte-identical to the product's, and `test/export-targets.test.ts` proves it by building
 * the tree with `npx astro build` and comparing the emitted HTML with a live site response.
 * Without that assertion "same shell" would be a comment.
 *
 * `npx astro build` is run by the gate, not by the exporter: an exporter that built the
 * tree would ship a `dist/` the client cannot edit, which is the thing D24 refuses.
 */
import { existsSync, readFileSync } from 'node:fs';
import { join } from 'node:path';

import { pageCssPath } from './document.ts';
import { renderNotes } from './notes.ts';
import { assetFile, type Projection } from './project.ts';
import { filterLockfile, readSourceLock, resolvedVersion } from './lockfile.ts';
import { mediaFile } from './static.ts';
import type { TreeFile } from './tree.ts';
import { CSP_CONF_FILE, cspConf } from '../render/csp.ts';

export interface AstroOptions {
  projection: Projection;
  contentRoot: string;
  /** The platform's repository root — where the resolved `package-lock.json` lives. */
  repoRoot: string;
  origin?: string;
}

/**
 * The shell. One `<main set:html>` — the body is the fragment the projection produced,
 * inserted raw, exactly as `page.astro` does it. The blank line after `---` is Astro's
 * frontmatter terminator; the indentation below it is the document's indentation and is
 * what makes the bytes match (§11.1, D24).
 */
export function shellSource(tenantKey: string): string {
  return `---
/**
 * The page shell — generated by the Skunkworks exporter, editable.
 *
 * It is the same document the hosted product serves: one <head> with the page's title
 * and CSS, one <main> holding the body fragment. Edit it here and every page picks the
 * change up; that is the "runnable, editable project" half of D24.
 */
interface Props {
  title: string;
  path: string;
  /** S8s: the page's own stylesheet, as a URL — never the CSS text (see page.astro). */
  cssHref: string | null;
  body: string;
}
const { title, path, cssHref, body } = Astro.props as Props;
const tenantKey = ${JSON.stringify(tenantKey)};
---
<!DOCTYPE html>
<html lang="en" data-tenant={tenantKey}>
  <head>
    <meta charset="utf-8">
    <meta name="viewport" content="width=device-width, initial-scale=1">
    <title>{title}</title>{cssHref !== null ? <link rel="stylesheet" href={cssHref} /> : null}
  </head>
  <body data-page-path={path}>
    <main set:html={body} />
  </body>
</html>
`;
}

/** One page: a frontmatter import of the fragment, then the shell call. */
export function pageSource(page: { path: string; title: string; bodyCss: string }, fragment: string): string {
  // Expressions, not string attributes: a title or a CSS rule may carry a quote, and an
  // HTML attribute has no backslash escape. `{...}` is JavaScript, and Astro escapes the
  // result the way the product's `<title>{page.title}</title>` is escaped.
  return `---
import Shell from '../components/Shell.astro';
import body from '../content/pages/${fragment}?raw';
---
<Shell title={${JSON.stringify(page.title)}} path={${JSON.stringify(page.path)}} cssHref={${JSON.stringify(page.bodyCss === '' ? null : pageCssPath(page.bodyCss))}} body={body} />
`;
}

/** `/` → `index.astro`; `/about` → `about.astro`; `/blog/post` → `blog/post.astro`. */
export function astroPageFile(path: string): string {
  if (path === '/') return 'index.astro';
  return `${path.replace(/^\//, '')}.astro`;
}

/** `/about` → `about.html`; `/` → `index.html` — the fragment's file name. */
export function fragmentFile(path: string): string {
  if (path === '/') return 'index.html';
  return `${path.replace(/^\//, '')}.html`;
}

const README = `# The exported site

This is a static [Astro](https://astro.build) project: real source, not a pre-built
bundle. \`npx astro build\` writes \`dist/\`, and \`dist/\` is what a web server serves.

## Run it

    npm ci
    npm run build      # writes dist/
    npm run preview    # serves dist/ locally

\`npm run dev\` gives you the live editor with hot reload while you make changes.

## Edit it

- **A page's content** is \`src/content/pages/<name>.html\` — an HTML fragment, the same
  bytes the hosted editor stores. Edit it directly.
- **The shell** is \`src/components/Shell.astro\` — the \`<head>\`, the \`<main>\`, the
  \`<style>\` block. One edit applies to every page.
- **A page's URL, title and CSS** are in its \`src/pages/<name>.astro\` file, in the
  \`<Shell … />\` call.

Add a page by adding \`src/pages/<name>.astro\` and \`src/content/pages/<name>.html\`.

## Media

The images and files are under \`public/media/\`, at the paths the pages already
reference (\`/media/<key>.<ext>\`). Replacing a file with the same name replaces the
image everywhere; there is no build step for media.
`;

const CONFIG = `import { defineConfig } from 'astro/config';

// A **static** build: the client's server runs no Node process (SDS §11.1, last row).
// \`compressHTML: false\` is not cosmetic — the hosted product serves its shell with the
// template's own whitespace, and the export gate asserts the built document is
// byte-identical to a live response.
export default defineConfig({
  output: 'static',
  srcDir: './src',
  publicDir: './public',
  outDir: './dist',
  build: { format: 'directory' },
  trailingSlash: 'ignore',
  compressHTML: false,
  devToolbar: { enabled: false },
});
`;

/**
 * The astro version this tree pins, and the lockfile it pins it with.
 *
 * The image may ship `node_modules` without the `package-lock.json` that produced it; an
 * exporter that refused to cut an Astro project for that reason would be refusing over a
 * file the client does not need. So: the resolved lock when it is there (the pin and every
 * `integrity` are then the ones the build used), else the version actually installed, else
 * the range the repository declares — and `EXPORT-NOTES.md` says when there is no lock, with
 * `npm install` as the instruction. It never writes a lock it did not resolve.
 */
export function astroVersionFor(repoRoot: string): { version: string; lock: ReturnType<typeof readSourceLock> | null } {
  const installed = join(repoRoot, 'node_modules', 'astro', 'package.json');
  const lockPath = join(repoRoot, 'package-lock.json');
  const lock = existsSync(lockPath) ? readSourceLock(repoRoot) : null;
  const pinned = lock === null ? null : resolvedVersion(lock, 'astro');
  if (pinned !== null) return { version: pinned, lock };
  if (existsSync(installed)) {
    const pkg = JSON.parse(readFileSync(installed, 'utf8')) as { version?: string };
    if (typeof pkg.version === 'string' && pkg.version !== '') return { version: pkg.version, lock: null };
  }
  const declared = JSON.parse(readFileSync(join(repoRoot, 'package.json'), 'utf8')) as {
    dependencies?: Record<string, string>;
  };
  const range = declared.dependencies?.astro ?? declared.dependencies?.['astro'];
  if (range === undefined) throw new Error('no astro version to pin: no lock entry, no node_modules/astro, no dependency');
  return { version: range.replace(/^[^0-9]*/, ''), lock: null };
}

export function planAstro(options: AstroOptions): TreeFile[] {
  const { projection } = options;
  const files: TreeFile[] = [];

  const resolved = astroVersionFor(options.repoRoot);
  const deps = { astro: resolved.version };
  const filtered = resolved.lock === null ? null : filterLockfile(resolved.lock, ['astro'], deps);

  files.push({
    path: 'package.json',
    bytes: `${JSON.stringify(
      {
        name: `${projection.tenantKey}-site`,
        private: true,
        type: 'module',
        scripts: { build: 'astro build', dev: 'astro dev', preview: 'astro preview' },
        dependencies: deps,
      },
      null,
      2,
    )}\n`,
  });
  if (filtered !== null) {
    files.push({ path: 'package-lock.json', bytes: `${JSON.stringify(filtered, null, 2)}\n` });
  }
  files.push({ path: 'astro.config.mjs', bytes: CONFIG });
  files.push({ path: 'src/components/Shell.astro', bytes: shellSource(projection.tenantKey) });

  for (const page of projection.pages) {
    files.push({ path: `src/pages/${astroPageFile(page.path)}`, bytes: pageSource(page, fragmentFile(page.path)) });
    files.push({ path: `src/content/pages/${fragmentFile(page.path)}`, bytes: page.bodyHtml });
  }

  // S8s: the stylesheets the pages name, in the project's `public/` — Astro serves that at `/`,
  // so `public/_css/<sha>.css` is the URL `pageCssPath()` returns.
  const sheets = new Map<string, string>();
  for (const page of projection.pages) {
    if (page.bodyCss !== '') sheets.set(pageCssPath(page.bodyCss), page.bodyCss);
  }
  for (const [path, css] of sheets) files.push({ path: `public${path}`, bytes: css });

  for (const asset of projection.referenced) {
    files.push({ path: `public/${mediaFile(asset.url)}`, bytes: readFileSync(assetFile(options.contentRoot, asset)) });
  }

  // §10.5 (C-12, S4c): the CSP line, byte-identical to the static tree's and the bundle's.
  files.push({ path: CSP_CONF_FILE, bytes: cspConf() });

  files.push({ path: 'README.md', bytes: README });
  files.push({
    path: 'EXPORT-NOTES.md',
    bytes: renderNotes({
      target: 'astro',
      projection,
      ...(options.origin === undefined ? {} : { origin: options.origin }),
      lines: [
        '- **Run:** `npm ci && npm run build`, then serve `dist/`. `npm run dev` edits live.',
        '- **Astro** is pinned to the version the exporter resolved; `package-lock.json` is that',
        '  lockfile filtered to the closure a static build needs — every `integrity` is the',
        '  resolved one. No dependency of the *product* travels (no `better-sqlite3`, `fastify`,',
        '  `grapesjs`, `pdf-lib`, `prettier`); `sharp` is in astro own closure, not ours.',
        filtered === null ? '- **No `package-lock.json`:** the resolved lock could not be filtered; run `npm install`.' : '',
        '- **No download plane:** a gated asset is refused at export (§11.3 #1), never omitted.',
      ].filter((line) => line !== ''),
    }),
  });

  return files;
}
